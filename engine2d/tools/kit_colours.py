"""
Kit colours for the 2D match engine, read off the club logos.

Writes HandballManager.Core/Engine2D/KitColours.Generated.cs: for every logo under
HandballManager/Assets/teamlogo, a primary and a secondary colour. The primary is the logo's
most common *coloured* area (a club's badge is nearly always in its colours); the secondary is
the next colour that stands apart from it, which may well be white or black.

Run from the repository root:  python tools/kit_colours.py
Hand corrections go in KitColours.cs (Overrides), never in the generated file.
"""
import colorsys
import os
from PIL import Image

ROOT = os.path.join("HandballManager", "Assets", "teamlogo")
OUT = os.path.join("HandballManager.Core", "Engine2D", "KitColours.Generated.cs")


def quantise(img, k=6):
    img = img.convert("RGBA")
    img.thumbnail((96, 96))
    px = [p for p in (img.get_flattened_data() if hasattr(img, "get_flattened_data") else img.getdata()) if p[3] >= 160]
    if not px:
        return []
    rgb = Image.new("RGB", (len(px), 1))
    rgb.putdata([p[:3] for p in px])
    q = rgb.quantize(colors=k, method=Image.Quantize.MEDIANCUT)
    pal = q.getpalette()
    counts = q.getcolors()
    out = []
    for count, idx in sorted(counts, reverse=True):
        r, g, b = pal[idx * 3: idx * 3 + 3]
        out.append((count / len(px), (r, g, b)))
    return out


def sat_light(c):
    h, l, s = colorsys.rgb_to_hls(*(x / 255 for x in c))
    return s, l


def distance(a, b):
    return sum((x - y) ** 2 for x, y in zip(a, b)) ** 0.5


def pick(colours):
    coloured = [(share, c) for share, c in colours
                if sat_light(c)[0] > 0.35 and 0.12 < sat_light(c)[1] < 0.88 and share > 0.04]
    primary = coloured[0][1] if coloured else colours[0][1]
    secondary = None
    for share, c in colours:
        if share > 0.03 and distance(c, primary) > 120:
            secondary = c
            break
    if secondary is None:
        # Nothing stands apart: white on a dark kit, black on a light one.
        secondary = (255, 255, 255) if sat_light(primary)[1] < 0.55 else (20, 20, 20)
    return primary, secondary


def hexc(c):
    return "#{:02X}{:02X}{:02X}".format(*c)


def main():
    rows = []
    for country in sorted(os.listdir(ROOT)):
        folder = os.path.join(ROOT, country)
        if not os.path.isdir(folder):
            continue
        for name in sorted(os.listdir(folder)):
            if not name.lower().endswith((".png", ".jpg", ".jpeg", ".webp")):
                continue
            try:
                colours = quantise(Image.open(os.path.join(folder, name)))
            except Exception as ex:  # a logo the tool cannot read keeps the default kit
                print(f"skip {country}/{name}: {ex}")
                continue
            if not colours:
                continue
            p, s = pick(colours)
            rows.append((f"{country}/{name}", hexc(p), hexc(s)))

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// <auto-generated>\n")
        f.write("// Written by tools/kit_colours.py from the club logos. Do not edit by hand:\n")
        f.write("// put corrections in KitColours.Overrides instead, and re-run the tool for new clubs.\n")
        f.write("// </auto-generated>\n")
        f.write("namespace HandballManager.Engine2D;\n\n")
        f.write("public static partial class KitColours\n{\n")
        f.write("    private static readonly Dictionary<string, (string Primary, string Secondary)> FromLogos = new(StringComparer.OrdinalIgnoreCase)\n    {\n")
        for key, p, s in rows:
            f.write(f'        ["{key}"] = ("{p}", "{s}"),\n')
        f.write("    };\n}\n")
    print(f"{len(rows)} clubs -> {OUT}")


if __name__ == "__main__":
    main()
